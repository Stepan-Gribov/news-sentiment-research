def select(row):
    old = row["industry"].strip()
    if not old:
        return "", "unknown_kept_blank"
    if row["company"] in OVERRIDES:
        return OVERRIDES[row["company"]], "issuer_specific_review"
    terms = {x.strip() for x in old.split(";") if x.strip()}
    for industry, selectors in RULES:
        if terms & selectors:
            return industry, "reviewed_sector_taxonomy"
    # Generic funding SPVs are not assigned an operating sector without evidence.
    if terms <= {"облигация", "финансирование", "финансы"}:
        return "", "funding_vehicle_operating_sector_unknown"
    raise ValueError(f"Unreviewed industry group: {row['company']}: {old}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    original = pq.read_table(args.registry).to_pylist()
    updated, audit, original_overrides = [], [], {}
    for row in original:
        industry, reason = select(row)
        assert not any(c in industry for c in ";,|\n")
        new = dict(row, industry=industry)
        updated.append(new)
        audit.append(dict(company_id=row["company_id"], company=row["company"], previous_industry=row["industry"], industry=industry, reason=reason, verification_url=SOURCES.get(row["company"], "")))
        for old_id in row["old_company_ids"].split("; "):
            original_overrides[old_id] = dict(industry=industry)
        assert all(row[k] == new[k] for k in row if k != "industry")
    args.output_dir.mkdir(parents=True, exist_ok=False)
    policy = dict(version="20261006_single_industry_01", canonical_industries={r["company_id"]:r["industry"] for r in updated}, original_company_overrides=original_overrides, industry_search_scope="title", products_policy="identical_to_previous_bank_topics", selection_note="Reviewed existing business descriptions; issuer exceptions override sector rules; unknown sectors stay blank. Static dominant-sector classification, not historical point-in-time labels.")
    for filename, content in [("single_industry_policy.json",policy),("company_registry_single_industry.json",updated),("industry_selection_audit.json",audit)]:
        (args.output_dir/filename).write_text(json.dumps(content,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    pq.write_table(pa.Table.from_pylist(updated), args.output_dir/"company_registry_single_industry.parquet", compression="snappy")
    pq.write_table(pa.Table.from_pylist(audit), args.output_dir/"industry_selection_audit.parquet", compression="snappy")
    report = dict(companies=len(updated),classified=sum(bool(r["industry"]) for r in updated),blank=sum(not r["industry"] for r in updated),industry_counts=dict(collections.Counter(r["industry"] for r in updated)),unchanged_fields=[k for k in original[0] if k!="industry"])
    (args.output_dir/"preparation_audit.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,ensure_ascii=False))

if __name__ == "__main__":
    main()
